/** Baseline noise and a peak near the quantitation limit. */
const noiseFig = () => {
  const w = 620, h = 220;
  const ax = axes({ w, h, xmin: 0, xmax: 10, ymin: -1.5, ymax: 6, xticks: [0, 2, 4, 6, 8, 10], yticks: [], xlabel: "Retention time (min)", ylabel: "Response" });
  const pts = trace({ sx: ax.sx, sy: ax.sy, tmin: 0, tmax: 10, peaks: [{ t0: 6.2, h: 4.2, s: 0.12 }], noise: 0.21, seed: 11, n: 900 });
  let s = ax.frame + path(pts, { stroke: C.navy, width: 1.1 });
  s += `<rect x="${ax.sx(1)}" y="${ax.sy(0.42)}" width="${ax.sx(4.5) - ax.sx(1)}" height="${ax.sy(-0.42) - ax.sy(0.42)}" fill="${C.teal}" fill-opacity=".12" stroke="${C.teal}" stroke-dasharray="4 3"/>`;
  s += T((ax.sx(1) + ax.sx(4.5)) / 2, ax.sy(1.1), "noise window (h = peak-to-peak)", { size: 9, fill: C.tealD, weight: 600 });
  s += `<line x1="${ax.sx(7)}" y1="${ax.sy(0)}" x2="${ax.sx(7)}" y2="${ax.sy(4.2)}" stroke="${C.gold}" stroke-width="1.4"/>`;
  s += T(ax.sx(7.15), ax.sy(2.3), "H", { size: 10, anchor: "start", fill: C.goldD, weight: 700 });
  s += T(ax.sx(8.7), ax.sy(4.8), "S/N = 2H / h ≈ 10", { size: 9.5, fill: C.navy, weight: 700 });
  return svg(w, h, s);
};

