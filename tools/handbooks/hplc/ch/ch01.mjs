// Figure 1-2: two equal peaks at increasing resolution.
function figRes() {
  const W = 560, H = 150, cells = [0.6, 1.0, 1.5, 2.0];
  let g = "";
  cells.forEach((rs, i) => {
    const ox = 10 + i * 138, s = 0.18, d = 4 * s * rs, c = 1.5;
    const sx = (t) => ox + (t / 3) * 128, sy = (v) => 118 - v * 86;
    const pts = [], p1 = [], p2 = [];
    for (let j = 0; j <= 240; j++) {
      const t = (3 * j) / 240, a = peakAt(t, { t0: c - d / 2, h: 1, s }), b = peakAt(t, { t0: c + d / 2, h: 1, s });
      pts.push([sx(t), sy(a + b)]); p1.push([sx(t), sy(a)]); p2.push([sx(t), sy(b)]);
    }
    g += `<rect x="${ox - 4}" y="8" width="132" height="128" rx="6" fill="${i === 2 ? C.tealXL : "#f7f9fc"}" stroke="${C.line}"/>`;
    g += path(p1, { stroke: C.teal, width: 1, dash: "3 2" }) + path(p2, { stroke: C.gold, width: 1, dash: "3 2" }) + path(pts, { stroke: C.navy, width: 1.6 });
    g += `<line x1="${ox}" y1="118" x2="${ox + 124}" y2="118" stroke="${C.muted}" stroke-width=".8"/>`;
    g += T(ox + 62, 132, `R<tspan font-size="7" dy="2">s</tspan><tspan dy="-2"> = ${rs.toFixed(1)}</tspan>`, { size: 10, fill: C.navy, weight: 700 });
  });
  return svg(W, H, g);
}

// Figure 1-3: van Deemter curves for three particle sizes.
function figVD() {
  const W = 560, H = 270, Dm = 1e-9, A = 1, B = 2, Cc = 0.08;
  const a = axes({ w: W, h: H, x0: 52, xmin: 0, xmax: 6, ymin: 0, ymax: 30, xticks: [0, 1, 2, 3, 4, 5, 6], yticks: [0, 5, 10, 15, 20, 25, 30], xlabel: "Linear velocity u (mm/s)", ylabel: "Plate height H (µm)" });
  const Hf = (u, dp) => dp * 1e6 * (A + (B * Dm) / (u * 1e-3 * dp) + (Cc * u * 1e-3 * dp) / Dm);
  const curves = [[5e-6, C.navy, "5 µm"], [3e-6, C.teal, "3 µm"], [1.7e-6, C.gold, "1.7 µm"]];
  let g = a.frame;
  for (const [dp, col, lab] of curves) {
    const pts = [];
    for (let u = 0.12; u <= 6; u += 0.02) {
      const h = Hf(u, dp);
      if (h <= 30) pts.push([a.sx(u), a.sy(h)]);
    }
    g += path(pts, { stroke: col, width: 2 });
    const uo = Math.sqrt(B / Cc) * Dm / dp * 1e3;
    g += `<circle cx="${a.sx(uo)}" cy="${a.sy(Hf(uo, dp))}" r="3.2" fill="${col}"/>`;
  }
  // Terms for the 5 µm curve.
  const dp = 5e-6, tA = [], tB = [], tC = [];
  for (let u = 0.2; u <= 6; u += 0.05) {
    tA.push([a.sx(u), a.sy(dp * 1e6 * A)]);
    const b = (dp * 1e6 * B * Dm) / (u * 1e-3 * dp);
    if (b < 30) tB.push([a.sx(u), a.sy(b)]);
    tC.push([a.sx(u), a.sy((dp * 1e6 * Cc * u * 1e-3 * dp) / Dm)]);
  }
  g += path(tA, { stroke: C.muted, width: 1, dash: "4 3" }) + path(tB, { stroke: C.muted, width: 1, dash: "4 3" }) + path(tC, { stroke: C.muted, width: 1, dash: "4 3" });
  g += T(a.sx(5.6), a.sy(5) - 4, "A", { size: 9, fill: C.muted, weight: 700 }) + T(a.sx(0.45), a.sy(22), "B/u", { size: 9, fill: C.muted, weight: 700, anchor: "start" }) + T(a.sx(5.5), a.sy(11) - 6, "C·u", { size: 9, fill: C.muted, weight: 700 });
  curves.forEach(([, col, lab], i) => (g += `<rect x="${a.x1 - 120}" y="${a.y0 + 6 + i * 16}" width="14" height="3" fill="${col}"/>` + T(a.x1 - 100, a.y0 + 11 + i * 16, `d<tspan font-size="6" dy="2">p</tspan><tspan dy="-2"> = ${lab}</tspan>`, { size: 9, anchor: "start" })));
  g += T(a.x1 - 120, a.y0 + 62, "● optimum velocity", { size: 8, fill: C.muted, anchor: "start" });
  return svg(W, H, g);
}

// Figure 1-4: tailing factor geometry at 5 % height.
function figTail() {
  const W = 520, H = 230;
  const a = axes({ w: W, h: H, x0: 30, x1: W - 20, xmin: 2.4, xmax: 4.4, ymin: -3, ymax: 108, xticks: [], yticks: [], grid: false });
  const pk = { t0: 3.0, h: 100, s: 0.07, tau: 0.12 };
  const tr = trace({ sx: a.sx, sy: a.sy, tmin: 2.4, tmax: 4.4, peaks: [pk], n: 800 });
  // Locate apex and 5 % crossings numerically on the trace.
  let iMax = 0;
  tr.forEach((q, i) => q[1] < tr[iMax][1] && (iMax = i));
  const yApex = tr[iMax][1], y0 = a.sy(0), y5 = y0 - 0.05 * (y0 - yApex);
  let iL = iMax, iR = iMax;
  while (iL > 0 && tr[iL][1] < y5) iL--;
  while (iR < tr.length - 1 && tr[iR][1] < y5) iR++;
  const xA = tr[iMax][0], xL = tr[iL][0], xR = tr[iR][0];
  return svg(W, H, `${arrowDefs("a4", C.tealD)}${a.frame}${path(tr, { stroke: C.navy, width: 2 })}
  <line x1="${xA}" y1="${yApex}" x2="${xA}" y2="${y0}" stroke="${C.muted}" stroke-dasharray="3 3"/>
  <line x1="${xL - 30}" y1="${y5}" x2="${xR + 30}" y2="${y5}" stroke="${C.gold}" stroke-width="1"/>${T(xR + 34, y5 + 3, "5 % h", { size: 8.5, fill: C.goldD, anchor: "start", weight: 700 })}
  <path d="M${xL} ${y5 + 18}H${xA}" stroke="${C.tealD}" marker-start="url(#a4)" marker-end="url(#a4)"/>${T((xL + xA) / 2, y5 + 32, "f", { size: 10, fill: C.tealD, weight: 700 })}
  <path d="M${xL} ${y5 - 16}H${xR}" stroke="${C.navy}" marker-start="url(#a4)" marker-end="url(#a4)"/>${T((xL + xR) / 2, y5 - 21, "W<tspan font-size='6.5' dy='2'>0.05</tspan>", { size: 10, fill: C.navy, weight: 700 })}
  ${T(W - 30, 40, "T = W<tspan font-size='7' dy='2'>0.05</tspan><tspan dy='-2'> / 2f</tspan>", { size: 12, fill: C.navy, anchor: "end", weight: 700 })}
  ${T(W - 30, 58, `in this example T ≈ ${((xR - xL) / (2 * (xA - xL))).toFixed(1)}`, { size: 9, fill: C.muted, anchor: "end" })}`);
}

