// Figure 8-1: a bracketed analytical sequence.
function figSeq() {
  const W = 580, H = 120;
  const items = [
    ["BL", "blank", "#e7ecf2", C.navy], ["SST", "×5–6", C.tealXL, C.tealD], ["STD", "check", C.goldL, C.goldD],
    ["S1", "", "#fff", C.navy], ["S2", "", "#fff", C.navy], ["S3", "", "#fff", C.navy], ["S4", "", "#fff", C.navy],
    ["STD", "bracket", C.goldL, C.goldD], ["S5", "", "#fff", C.navy], ["S6", "", "#fff", C.navy], ["S7", "", "#fff", C.navy], ["S8", "", "#fff", C.navy],
    ["STD", "bracket", C.goldL, C.goldD], ["BL", "end", "#e7ecf2", C.navy],
  ];
  let g = "";
  items.forEach(([t, s, f, c], i) => {
    const x = 8 + i * 40.5;
    g += `<rect x="${x}" y="30" width="36" height="40" rx="6" fill="${f}" stroke="${c}" stroke-width="1.3"/>` + T(x + 18, 54, t, { size: 9, fill: c, weight: 700 }) + (s ? T(x + 18, 86, s, { size: 7, fill: C.muted }) : "");
  });
  g += `<path d="M130 100H296" stroke="${C.gold}" stroke-width="1.4"/><path d="M296 100H500" stroke="${C.gold}" stroke-width="1.4" stroke-dasharray="4 3"/>` + T(300, 114, "each sample group is bracketed by standards that must meet the drift criterion", { size: 8, fill: C.goldD });
  g += T(290, 16, "Typical assay sequence", { size: 9.5, fill: C.navy, weight: 700 });
  return svg(W, H, g);
}

// Figure 8-2: integration of a partly resolved pair.
function figInt() {
  const W = 580, H = 190;
  const panel = (ox, title, mode) => {
    const sx = (t) => ox + 10 + ((t - 3.3) / 1.6) * 166, sy = (v) => 150 - v * 1.15;
    const pk = [{ t0: 3.9, h: 100, s: 0.08, tau: 0.05 }, { t0: 4.25, h: 30, s: 0.07 }];
    const tr = trace({ sx, sy, tmin: 3.3, tmax: 4.9, peaks: pk, n: 400 });
    // Valley point between the peaks.
    let iv = 0;
    tr.forEach(([x, y], i) => { const t = 3.3 + (1.6 * i) / 400; if (t > 4.0 && t < 4.22 && (iv === 0 || y > tr[iv][1])) iv = i; });
    const [xv, yv] = tr[iv];
    let s = `<rect x="${ox}" y="4" width="186" height="182" rx="7" fill="#f8fafc" stroke="${C.line}"/>` + T(ox + 93, 20, title, { size: 9, weight: 700, fill: C.navy });
    s += path(tr, { stroke: C.navy, width: 1.6 }) + `<line x1="${ox + 10}" y1="150" x2="${ox + 176}" y2="150" stroke="${C.muted}" stroke-width=".8"/>`;
    if (mode === "drop") s += `<line x1="${xv}" y1="${yv}" x2="${xv}" y2="150" stroke="${C.red}" stroke-width="1.5"/>`;
    if (mode === "skim") {
      const xe = sx(4.55), ye = tr[Math.round(((4.55 - 3.3) / 1.6) * 400)][1];
      s += `<line x1="${xv}" y1="${yv}" x2="${xe}" y2="${ye}" stroke="${C.red}" stroke-width="1.5"/><line x1="${xv}" y1="${yv}" x2="${xv}" y2="150" stroke="${C.red}" stroke-width=".8" stroke-dasharray="2 2"/>`;
    }
    if (mode === "valley") s += `<line x1="${sx(3.45)}" y1="150" x2="${xv}" y2="${yv}" stroke="${C.red}" stroke-width="1.5"/><line x1="${xv}" y1="${yv}" x2="${sx(4.6)}" y2="150" stroke="${C.red}" stroke-width="1.5"/>`;
    return s;
  };
  return svg(W, H, panel(4, "drop perpendicular", "drop") + panel(198, "tangent skim", "skim") + panel(392, "valley to valley", "valley"));
}

