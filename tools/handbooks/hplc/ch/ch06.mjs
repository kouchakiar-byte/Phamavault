// Figure 6-1: signal-to-noise measurement.
function figSN() {
  const W = 560, H = 220;
  const a = axes({ w: W, h: H, x0: 40, xmin: 0, xmax: 10, ymin: -2.5, ymax: 9, xticks: [], yticks: [], grid: false });
  const pk = [{ t0: 5, h: 6.5, s: 0.12 }];
  const tr = trace({ sx: a.sx, sy: a.sy, tmin: 0, tmax: 10, peaks: pk, noise: 0.42, n: 900, seed: 11 });
  let g = arrowDefs("s1", C.tealD) + a.frame + `<rect x="${a.sx(5 - 1.4)}" y="${a.y0}" width="${a.sx(5 + 1.4) - a.sx(5 - 1.4)}" height="${a.y1 - a.y0}" fill="${C.goldL}" opacity=".8"/>` + path(tr, { stroke: C.navy, width: 1.2 });
  g += `<line x1="${a.sx(5)}" y1="${a.sy(6.5)}" x2="${a.sx(5)}" y2="${a.sy(0)}" stroke="${C.tealD}" stroke-width="1.4" marker-start="url(#s1)" marker-end="url(#s1)"/>` + T(a.sx(5) + 8, a.sy(3.4), "H", { size: 11, fill: C.tealD, weight: 700, anchor: "start" });
  g += `<line x1="${a.sx(0.4)}" y1="${a.sy(0.85)}" x2="${a.sx(3.4)}" y2="${a.sy(0.85)}" stroke="${C.red}" stroke-dasharray="3 2"/><line x1="${a.sx(0.4)}" y1="${a.sy(-0.85)}" x2="${a.sx(3.4)}" y2="${a.sy(-0.85)}" stroke="${C.red}" stroke-dasharray="3 2"/>`;
  g += `<line x1="${a.sx(2)}" y1="${a.sy(0.85)}" x2="${a.sx(2)}" y2="${a.sy(-0.85)}" stroke="${C.red}" stroke-width="1.3" marker-start="url(#s1)" marker-end="url(#s1)"/>` + T(a.sx(2) + 6, a.sy(1.6), "h (noise range)", { size: 9, fill: C.red, weight: 700, anchor: "start" });
  g += T(a.sx(5), a.y0 + 12, "window ≥ 5 × w<tspan font-size='6' dy='2'>h</tspan>", { size: 8.5, fill: C.goldD, weight: 700 });
  g += T(a.x1 - 6, a.y0 + 30, "S/N = 2H / h", { size: 12, fill: C.navy, weight: 700, anchor: "end" });
  return svg(W, H, g);
}

// Figure 6-2: peak-to-valley ratio for a small impurity on the tail of the main peak.
function figPV() {
  const W = 520, H = 210;
  const a = axes({ w: W, h: H, x0: 40, xmin: 3, xmax: 6, ymin: -2, ymax: 40, xticks: [], yticks: [], grid: false });
  const pk = [{ t0: 4.0, h: 160, s: 0.1, tau: 0.08 }, { t0: 4.62, h: 16, s: 0.07 }];
  const tr = trace({ sx: a.sx, sy: a.sy, tmin: 3, tmax: 6, peaks: pk, n: 900 });
  // Valley and impurity apex from the trace.
  let iV = 0, iP = 0;
  tr.forEach(([x, y], i) => {
    const t = 3 + (3 * i) / 900;
    if (t > 4.35 && t < 4.6 && (iV === 0 || y > tr[iV][1])) iV = i;
    if (t > 4.5 && t < 4.75 && (iP === 0 || y < tr[iP][1])) iP = i;
  });
  const y0 = a.sy(0), [xv, yv] = tr[iV], [xp, yp] = tr[iP];
  let g = arrowDefs("s2", C.tealD) + a.frame + `<clipPath id="pv"><rect x="${a.x0}" y="${a.y0}" width="${a.x1 - a.x0}" height="${a.y1 - a.y0}"/></clipPath><g clip-path="url(#pv)">${path(tr, { stroke: C.navy, width: 1.8 })}</g>`;
  g += `<line x1="${xp}" y1="${yp}" x2="${xp}" y2="${y0}" stroke="${C.tealD}" stroke-width="1.3" marker-start="url(#s2)" marker-end="url(#s2)"/>` + T(xp + 7, (yp + y0) / 2, "H<tspan font-size='6' dy='2'>p</tspan>", { size: 10, fill: C.tealD, weight: 700, anchor: "start" });
  g += `<line x1="${xv}" y1="${yv}" x2="${xv}" y2="${y0}" stroke="${C.gold}" stroke-width="1.3" marker-start="url(#s2)" marker-end="url(#s2)"/>` + T(xv - 7, (yv + y0) / 2 + 10, "H<tspan font-size='6' dy='2'>v</tspan>", { size: 10, fill: C.goldD, weight: 700, anchor: "end" });
  g += T(a.x1 - 6, a.y0 + 18, "p/v = H<tspan font-size='7' dy='2'>p</tspan><tspan dy='-2'> / H</tspan><tspan font-size='7' dy='2'>v</tspan>", { size: 12, fill: C.navy, weight: 700, anchor: "end" });
  g += T(a.sx(3.75), a.y0 + 18, "main peak (off scale)", { size: 8, fill: C.muted });
  return svg(W, H, g);
}

const rsd = (B, n) => {
  const t = { 3: 2.92, 4: 2.353, 5: 2.132, 6: 2.015 }[n];
  return ((0.349 * B * Math.sqrt(n)) / t).toFixed(2);
};

