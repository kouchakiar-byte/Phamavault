// Figure 6-1: IR staging decision flow.
function figStages() {
  const W = 580, H = 260;
  let g = arrowDefs("s1", C.tealD) + arrowDefs("s2", C.red);
  const b = (x, y, w, h, lines, f = "#f8fafc", s = C.navy) =>
    `<rect x="${x}" y="${y}" width="${w}" height="${h}" rx="8" fill="${f}" stroke="${s}" stroke-width="1.3"/>` +
    lines.map((l, i) => T(x + w / 2, y + 20 + i * 13, l, { size: i ? 7.6 : 8.8, weight: i ? 400 : 700, fill: i ? C.muted : C.navy })).join("");
  const ar = (d, l, lx, ly, fail = false) => `<path d="${d}" fill="none" stroke="${fail ? C.red : C.tealD}" stroke-width="1.4" marker-end="url(#${fail ? "s2" : "s1"})"/>` + T(lx, ly, l, { size: 7.5, fill: fail ? C.red : C.tealD, weight: 700 });
  g += b(10, 16, 150, 60, ["S1: 6 units", "each ≥ Q + 5%"]);
  g += b(215, 16, 150, 60, ["S2: + 6 units (12)", "mean ≥ Q", "none < Q − 15%"]);
  g += b(420, 16, 150, 60, ["S3: + 12 units (24)", "mean ≥ Q; ≤ 2 < Q − 15%", "none < Q − 25%"]);
  g += b(215, 190, 150, 50, ["Passes", "release the batch"], C.tealXL, C.tealD) + b(420, 190, 150, 50, ["Fails", "OOS investigation"], "#fbefec", C.red);
  g += ar("M160 46H213", "fail", 186, 40, true) + ar("M365 46H418", "fail", 391, 40, true);
  g += ar("M85 78V215H213", "pass", 98, 150);
  g += ar("M290 78V188", "pass", 303, 140);
  g += ar("M470 78V130H330V188", "pass", 400, 124);
  g += ar("M530 78V188", "fail", 543, 140, true);
  return svg(W, H, g);
}

