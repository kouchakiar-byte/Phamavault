import { C, chapter, p, caseStudy, fig, svg, T, axes, path } from "../lib.mjs";

const line = (a, xs, ys, col, dash = "") => path(xs.map((x, i) => [a.sx(x), a.sy(ys[i])]), { stroke: col, width: 2, dash }) + xs.map((x, i) => `<circle cx="${a.sx(x)}" cy="${a.sy(ys[i])}" r="3" fill="${col}"/>`).join("");
const legend = (a, items, x, y) => items.map(([c, l], i) => `<rect x="${x}" y="${y + i * 15}" width="14" height="3" fill="${c}"/>` + T(x + 20, y + 5 + i * 15, l, { size: 8.5, anchor: "start" })).join("");

function fCone() {
  const W = 540, H = 200;
  const a = axes({ w: W, h: H, x0: 52, xmin: 0, xmax: 80, ymin: 0, ymax: 105, xticks: [0, 10, 20, 30, 45, 60, 75], yticks: [0, 20, 40, 60, 80, 100], xlabel: "Time (min)", ylabel: "Dissolved (%)" });
  const t = [10, 20, 30, 45, 60, 75], y50 = [55, 72, 79, 81, 82, 99], y75 = [63, 85, 94, 97, 98, 99];
  let g = a.frame + `<rect x="${a.sx(60)}" y="${a.y0}" width="${a.sx(75) - a.sx(60)}" height="${a.y1 - a.y0}" fill="${C.gold}" fill-opacity=".1"/>` + T(a.sx(67.5), a.y0 + 12, "250 rpm", { size: 8, fill: C.goldD, weight: 700 });
  g += line(a, t, y50, C.red) + line(a, t, y75, C.teal, "5 3") + legend(a, [[C.red, "50 rpm"], [C.teal, "75 rpm"]], a.x0 + 260, a.y1 - 40);
  return svg(W, H, g);
}

function fXlink() {
  const W = 540, H = 200;
  const a = axes({ w: W, h: H, x0: 52, xmin: 0, xmax: 60, ymin: 0, ymax: 105, xticks: [0, 10, 15, 20, 30, 45, 60], yticks: [0, 20, 40, 60, 80, 100], xlabel: "Time (min)", ylabel: "Dissolved (%)" });
  const t = [10, 15, 20, 30, 45, 60];
  let g = a.frame + line(a, t, [70, 86, 92, 97, 99, 99], C.teal) + line(a, t, [8, 15, 24, 41, 58, 68], C.red) + line(a, t, [52, 74, 86, 94, 98, 99], C.navy, "5 3");
  g += legend(a, [[C.teal, "initial"], [C.red, "6 M at 40 °C / 75 % RH"], [C.navy, "6 M, with pepsin"]], a.x0 + 250, a.y1 - 56);
  return svg(W, H, g);
}

